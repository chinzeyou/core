int	ft_isalnum(char c)
{
	if (c >= '0' && c <= '9')
		return (1);
	else if (c >= 'a' && c <= 'z')
		return (1);
	else if (c >= 'Z' && c <= 'Z')
		return (1);
	else
		return (0);
}
